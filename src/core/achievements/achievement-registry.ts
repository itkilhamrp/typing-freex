/**
 * Achievement Registry
 * Static definitions for all achievements and advancements in Typing FreeX.
 * Pure TypeScript, zero external dependencies.
 */

export type AchievementCategory = 'achievement' | 'advancement';
export type AchievementTier = number; // 0=locked, 1..3=bronze, 4..6=silver, 7..10=gold, 11..15=platinum, 16..20=diamond, 21..25=master, 26+=grandmaster

export type TrophyShape =
  | 'cup'
  | 'star'
  | 'medal'
  | 'shield'
  | 'crown'
  | 'bolt'
  | 'flame'
  | 'gem'
  | 'scroll'
  | 'wreath';

export type AdvancementShape =
  | 'hex_badge'
  | 'pentagon'
  | 'compass'
  | 'sigil'
  | 'chevron'
  | 'crest'
  | 'prism'
  | 'gear'
  | 'atom'
  | 'rune';

export type AchievementGroup =
  | 'speed'
  | 'accuracy'
  | 'endurance'
  | 'consistency'
  | 'exploration'
  | 'milestones'
  | 'special';

export interface TierDefinition {
  tier: AchievementTier;
  target: number;
  labelKey: string;
  descKey: string;
}

export interface AchievementDefinition {
  id: string;
  category: AchievementCategory;
  group: AchievementGroup;
  icon: string;
  trophyShape: TrophyShape;
  advancementShape?: AdvancementShape;
  tiers: TierDefinition[];
  eligibleModes?: string[];
  minDuration?: number;
  minWordCount?: number;
}

